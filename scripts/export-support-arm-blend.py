# Exports the Workstation Support Arm from SupportArm.blend into
# src/features/systainer/supportArmMesh.ts (positions in 0.01 mm as Int16, triangle indices, a part
# class per triangle), for the Systainer catalogue (catalog.ts `supportArm`).
#
# Usage (Blender 4.2+ / 5.x, headless; the .blend is not modified):
#   /Applications/Blender.app/Contents/MacOS/Blender -b ~/Documents/Blender/SupportArm.blend \
#     --python scripts/export-support-arm-blend.py -- src/features/systainer/supportArmMesh.ts
#
# The .blend is in mm (1 BU = 1 m, so coordinates × 1000). Its frame: the bar runs toward −y with the
# pins at +y, up (standing) is +z, x is across the arm's thickness, centred. Exported are the visible
# meshes, evaluated (Cube carries its T-slot boolean, Circle its hex socket): Cube is the anodised
# body, Circle the drop-shaped knob, Circle.001 / Circle.002 the pins and Plane the plate behind the
# upper pin. The hidden cutters (Cube.001, hexbool) and helper box (Cube.003) are skipped.
#
# Output frame (the catalogue's: SUPPORT_ARM's traced outline, hubProfiles.ts): X = OX − y_blend
# (along the arm, pins at −X), Y = OY − z_blend (the outline's y; standing up is −Y),
# Z = x_blend + T / 2 (thickness, 0 … T). OX and OY centre the model's length and height on the
# outline's (the model is 175.9 × 75.5 to the outline's 176.2 × 75.9), then nudge it 0.2 mm each
# way to where the least of its side silhouette falls outside the outline (3.6 mm², at the corners).
import base64
import struct
import sys

import bmesh
import bpy

out_path = sys.argv[sys.argv.index('--') + 1] if '--' in sys.argv else 'supportArmMesh.ts'
OX = 17.43
OY = -10.15
T = 20.8

BODY, KNOB, PIN = 0, 1, 2
PARTS = {'Cube': BODY, 'Circle': KNOB, 'Circle.001': PIN, 'Circle.002': PIN, 'Plane': PIN}

dg = bpy.context.evaluated_depsgraph_get()
pos, idx, cls = [], [], []
for name, part in PARTS.items():
    o = bpy.data.objects[name]
    bm = bmesh.new()
    bm.from_object(o, dg)
    bm.transform(o.matrix_world)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    bm.verts.ensure_lookup_table()
    base = len(pos) // 3
    for v in bm.verts:
        p = v.co * 1000.0
        pos += [OX - p.y, OY - p.z, p.x + T / 2]
    for f in bm.faces:
        idx += [base + v.index for v in f.verts]
        cls.append(part)
    bm.free()

q = [round(v * 100) for v in pos]
assert max(abs(v) for v in q) < 32767
assert len(pos) // 3 < 65536
b64 = lambda b: base64.b64encode(b).decode('ascii')
p64 = b64(struct.pack('<%dh' % len(q), *q))
i64 = b64(struct.pack('<%dH' % len(idx), *idx))
c64 = b64(bytes(cls))

wrap = lambda s: '\n'.join("  '" + s[i:i + 100] + "' +" for i in range(0, len(s), 100)).rstrip(' +')
with open(out_path, 'w') as f:
    f.write(
        '// Generated by scripts/export-support-arm-blend.py from SupportArm.blend (the Workstation Support\n'
        '// Arm, modelled by the project owner). Do not edit by hand.\n'
        '//\n'
        '// Frame (mm): the traced lying outline\'s (SUPPORT_ARM, hubProfiles.ts): x along the arm with the\n'
        '// pins at −x, y the outline\'s y (standing, up is −y), z across the thickness, 0 … 20.8.\n'
        '// Positions are Int16 in 0.01 mm, indices Uint16, one part class per triangle (SUPPORT_ARM_PART).\n'
        'export const SUPPORT_ARM_PART = { body: 0, knob: 1, pin: 2 } as const\n\n'
        f'export const SUPPORT_ARM_COUNTS = {{ verts: {len(pos) // 3}, tris: {len(cls)} }}\n\n'
        f'export const SUPPORT_ARM_POS =\n{wrap(p64)}\n\n'
        f'export const SUPPORT_ARM_IDX =\n{wrap(i64)}\n\n'
        f'export const SUPPORT_ARM_CLS =\n{wrap(c64)}\n'
    )
counts = {k: cls.count(v) for k, v in (('body', BODY), ('knob', KNOB), ('pin', PIN))}
print('SUPPORT_ARM_EXPORT', out_path, len(pos) // 3, 'verts', len(cls), 'tris', counts)
